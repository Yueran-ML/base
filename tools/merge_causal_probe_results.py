#!/usr/bin/env python3
"""
Merge per-source causal-probe result CSVs into an n=12 combined file.

The original E7 (5 cells) and the E7 expansion (7 cells) are run as
separate probe roots so the two pipelines don't collide on disk.
After both have been analysed with ``causal_fourier_intervention.py``,
``causal_fourier_topk_spectrum.py``, and
``causal_fourier_freq_selectivity.py``, the per-analysis CSVs come
out in two parallel directories:

  results/causal_probe/intervention_results.csv             (n=5)
  results/causal_probe/intervention_topk_spectrum.csv       (n=5)
  results/causal_probe/intervention_freq_selectivity.csv    (n=5)

  results/causal_probe_expansion/intervention_results.csv          (n=7)
  results/causal_probe_expansion/intervention_topk_spectrum.csv    (n=7)
  results/causal_probe_expansion/intervention_freq_selectivity.csv (n=7)

This script concatenates the matching files row-wise and writes
``results/causal_probe_combined/<same_name>.csv`` with an extra
``source`` column ("original" / "expansion") so per-source slices are
still recoverable.

Usage
-----
  python tools/merge_causal_probe_results.py
  python tools/merge_causal_probe_results.py \
         --orig-root results/causal_probe \
         --exp-root  results/causal_probe_expansion \
         --out-root  results/causal_probe_combined

If a file exists in only one of the two source roots, it is copied
through unchanged with the appropriate ``source`` column added.

After merging, the headline numbers reported in §4.4 (Table 3 +
Table 4) of the paper can be regenerated by re-running the summary
block at the bottom of each analysis script on the merged CSV.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

FILES_TO_MERGE = [
    "intervention_results.csv",
    "intervention_topk_spectrum.csv",
    "intervention_freq_selectivity.csv",
]


def _read_csv_with_source(path: Path, source_tag: str) -> tuple[list[str], list[dict]]:
    """Return (fieldnames, rows) with a ``source`` column injected."""
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        rows = [dict(r, source=source_tag) for r in reader]
        fieldnames = list(reader.fieldnames or []) + ["source"]
    return fieldnames, rows


def _merge_one(name: str, orig_root: Path, exp_root: Path,
               out_root: Path) -> dict:
    """Merge a single CSV across the two probe roots."""
    orig_path = orig_root / name
    exp_path = exp_root / name

    if not orig_path.exists() and not exp_path.exists():
        print(f"  [skip] {name}: not found in either root")
        return {"name": name, "merged": False}

    rows: list[dict] = []
    fieldnames: list[str] = []
    n_orig = n_exp = 0

    if orig_path.exists():
        fn_o, rows_o = _read_csv_with_source(orig_path, "original")
        rows.extend(rows_o); n_orig = len(rows_o)
        if not fieldnames:
            fieldnames = fn_o
    else:
        print(f"  [warn] {name}: missing in orig root")

    if exp_path.exists():
        fn_e, rows_e = _read_csv_with_source(exp_path, "expansion")
        rows.extend(rows_e); n_exp = len(rows_e)
        # If orig was missing or had a smaller column set, take union.
        for col in fn_e:
            if col not in fieldnames:
                fieldnames.append(col)
    else:
        print(f"  [warn] {name}: missing in expansion root")

    out_root.mkdir(parents=True, exist_ok=True)
    out_path = out_root / name
    with open(out_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            # Fill missing columns with empty string for row compatibility.
            for col in fieldnames:
                r.setdefault(col, "")
            w.writerow(r)
    print(f"  [merge] {name}: n_orig={n_orig} + n_exp={n_exp} = "
          f"{len(rows)} rows -> {out_path}")
    return {"name": name, "merged": True,
            "n_orig": n_orig, "n_exp": n_exp, "n_total": len(rows)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--orig-root", default="results/causal_probe",
                        help="Directory holding the original 5-cell "
                             "intervention CSVs.")
    parser.add_argument("--exp-root", default="results/causal_probe_expansion",
                        help="Directory holding the 7-cell expansion "
                             "intervention CSVs.")
    parser.add_argument("--out-root", default="results/causal_probe_combined",
                        help="Output directory for the merged CSVs.")
    args = parser.parse_args()

    orig_root = Path(args.orig_root)
    exp_root = Path(args.exp_root)
    out_root = Path(args.out_root)

    print(f"Merging causal-probe results:")
    print(f"  orig: {orig_root}")
    print(f"  exp:  {exp_root}")
    print(f"  out:  {out_root}\n")

    summary = []
    for name in FILES_TO_MERGE:
        summary.append(_merge_one(name, orig_root, exp_root, out_root))

    print(f"\nDone. Merged {sum(1 for s in summary if s['merged'])} "
          f"of {len(FILES_TO_MERGE)} files.")


if __name__ == "__main__":
    main()
